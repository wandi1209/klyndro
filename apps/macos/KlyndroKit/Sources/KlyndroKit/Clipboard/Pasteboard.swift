import AppKit
import Foundation

/// Reads and writes the macOS pasteboard.
@MainActor
public protocol Pasteboard: AnyObject {
    /// Current plain-text content, or `nil` when the pasteboard holds something else.
    func read() -> ClipboardSnapshot?
    func write(text: String)
}

/// `NSPasteboard.general` adapter.
///
/// `changeCount` is the platform's own change signal, so we never hash the pasteboard ourselves
/// just to notice a change.
@MainActor
public final class SystemPasteboard: Pasteboard {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public func read() -> ClipboardSnapshot? {
        // Copies that carry no text (images, files) are not our concern in v1; reporting `nil`
        // keeps them from being sent as empty strings.
        guard let text = pasteboard.string(forType: .string) else { return nil }
        return ClipboardSnapshot(
            text: text,
            sensitive: Self.isSensitive(pasteboard),
            changeCount: pasteboard.changeCount
        )
    }

    public func write(text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    /// Reads the markers other apps set to ask that content not be recorded.
    ///
    /// macOS has no single "sensitive" flag like Android's `EXTRA_IS_SENSITIVE`; these are what
    /// password managers use. Treating them as sensitive is the conservative choice.
    static func isSensitive(_ pasteboard: NSPasteboard) -> Bool {
        let markers: [NSPasteboard.PasteboardType] = [
            .init("org.nspasteboard.ConcealedType"),
            .init("org.nspasteboard.TransientType"),
            .init("org.nspasteboard.AutoGeneratedType")
        ]
        return markers.contains { pasteboard.data(forType: $0) != nil }
    }
}

/// Polls the pasteboard while a session is connected.
///
/// Polling is the only public way to observe changes: `NSPasteboard` has no change notification.
/// The timer runs only while clipboard sync is active, so an idle Klyndro does no work.
@MainActor
public final class PasteboardMonitor {
    private let pasteboard: Pasteboard
    private let interval: Duration
    private let onChange: (ClipboardSnapshot) -> Void
    private var task: Task<Void, Never>?
    private var lastReportedChangeCount: Int?

    public init(
        pasteboard: Pasteboard,
        interval: Duration = .milliseconds(400),
        onChange: @escaping (ClipboardSnapshot) -> Void
    ) {
        self.pasteboard = pasteboard
        self.interval = interval
        self.onChange = onChange
    }

    public var isRunning: Bool { task != nil }

    public func start() {
        guard task == nil else { return }

        // Seed with the current value so whatever was on the pasteboard before connecting is not
        // replayed to the peer the moment we start.
        if let snapshot = pasteboard.read() {
            lastReportedChangeCount = snapshot.changeCount
        }

        task = Task { [weak self, interval] in
            while !Task.isCancelled {
                try? await Task.sleep(for: interval)
                guard let self, !Task.isCancelled else { return }
                self.poll()
            }
        }
    }

    public func stop() {
        task?.cancel()
        task = nil
    }

    /// Reads once and reports a change, if any.
    public func poll() {
        guard let snapshot = pasteboard.read() else { return }
        guard snapshot.changeCount != lastReportedChangeCount else { return }
        lastReportedChangeCount = snapshot.changeCount
        onChange(snapshot)
    }

    /// Records the current pasteboard state as already seen, after we wrote it ourselves.
    public func markCurrentAsSeen() {
        lastReportedChangeCount = pasteboard.read()?.changeCount
    }
}
